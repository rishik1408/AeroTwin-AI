"""
cmapss_benchmark.py — AeroTwin AI vs. NASA C-MAPSS validation benchmark.

Compares synthetic engine-fault degradation curves (generated by
generate_dataset.py) against real run-to-failure turbofan data from the
NASA C-MAPSS dataset using two complementary statistical tests:

  1. KS test on per-mission degradation *signatures*
     • Decline rate  — per-tick slope of the chosen sensor column during the
                       fault-active window (first fault onset → last fault row).
     • Noise-to-signal ratio — high-frequency residual variance relative to
                       the linear trend over that same window.
     Only fault missions are included (healthy missions have no degradation
     to compare). This avoids the artefact where the descent/shutdown phase
     creates a spurious "decline" at the end of every mission.

  2. RUL-vs-parameter correlation consistency
     For each mission the script computes a piecewise-linear RUL curve and
     correlates it with the chosen sensor column.  The distribution of those
     Pearson r values is compared between the C-MAPSS and synthetic datasets,
     and the mean ± std is printed so you can judge whether both datasets
     show a similarly-shaped RUL-vs-parameter relationship.

Usage:
    python cmapss_benchmark.py \\
        --cmapss      ../../data/cmapss/train_FD001.txt \\
        --synthetic   ../dataset/all_missions.csv \\
        --synthetic-col      oil_pressure_bar \\
        --synthetic-id-col   mission_id \\
        --synthetic-time-col tick

Pass/fail criterion (KS tests):
    p > 0.05 → distributions are statistically indistinguishable ✅
    p ≤ 0.05 → distributions differ significantly; tune faults.py ❌
"""

import argparse
import sys
from collections import defaultdict

import numpy as np

try:
    from scipy.stats import ks_2samp, pearsonr
except ImportError:
    sys.exit(
        "scipy is required.  Install it with:  pip install scipy\n"
        "or add it to simulation/requirements.txt and re-run pip install -r requirements.txt"
    )

# ---------------------------------------------------------------------------
# C-MAPSS helpers
# ---------------------------------------------------------------------------

# C-MAPSS column layout (1-indexed in the paper; 0-indexed here):
#   0  unit_number
#   1  time_in_cycles
#   2  op_setting_1
#   3  op_setting_2
#   4  op_setting_3
#   5..25  sensor_1 .. sensor_21
_CMAPSS_UNIT_COL  = 0
_CMAPSS_TIME_COL  = 1
_CMAPSS_SENSOR_START = 5   # first sensor column (sensor_1)


def load_cmapss(filepath: str) -> dict[int, np.ndarray]:
    """
    Load a C-MAPSS text file and return a dict mapping
    unit_number → 2-D float array (rows=time steps, cols=all columns).
    """
    units: dict[int, list[list[float]]] = defaultdict(list)
    with open(filepath, "r") as f:
        for line in f:
            parts = line.strip().split()
            if not parts:
                continue
            row = [float(x) for x in parts]
            unit = int(row[_CMAPSS_UNIT_COL])
            units[unit].append(row)
    return {u: np.array(rows) for u, rows in units.items()}


def add_piecewise_rul(unit_data: np.ndarray, early_rul_cap: int = 125) -> np.ndarray:
    """
    Append a RUL column to a C-MAPSS unit array.

    Uses the standard piecewise-linear (flat-then-declining) labelling
    strategy: RUL is capped at `early_rul_cap` for the early portion of
    the run, then counts down linearly to 0 at the final cycle.

    Returns a new array with the RUL column appended as the last column.
    """
    max_cycle   = int(unit_data[:, _CMAPSS_TIME_COL].max())
    time_cycles = unit_data[:, _CMAPSS_TIME_COL].astype(int)
    raw_rul     = max_cycle - time_cycles          # counts down to 0 at end
    rul         = np.minimum(raw_rul, early_rul_cap)
    return np.column_stack([unit_data, rul])


def extract_cmapss_signatures(
    units: dict[int, np.ndarray],
    sensor_col: int,
    window: int = 20,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    For every C-MAPSS unit, extract:
      • decline_rates   — per-cycle linear slope of `sensor_col` over the
                          last `window` cycles (the degradation tail).
      • noise_ratios    — residual std / |trend mean| over that window.
      • rul_correlations — Pearson r between the RUL column and sensor_col
                           across the whole run.

    C-MAPSS units always run to failure, so the last `window` rows are a
    valid fault-active window.
    """
    decline_rates:    list[float] = []
    noise_ratios:     list[float] = []
    rul_correlations: list[float] = []

    for unit_id, data in units.items():
        # Annotate with RUL
        data_rul = add_piecewise_rul(data)
        rul_col  = data_rul[:, -1]               # last column
        sensor   = data_rul[:, sensor_col]

        # ── degradation window (last `window` rows) ──────────────────────
        window_sensor = sensor[-window:]
        ticks = np.arange(len(window_sensor), dtype=float)

        if len(window_sensor) < 2:
            continue

        slope, _ = np.polyfit(ticks, window_sensor, 1)
        trend     = np.polyval([slope, _], ticks)
        residuals = window_sensor - trend
        signal_mean = abs(np.mean(trend))
        nsr = float(np.std(residuals) / signal_mean) if signal_mean > 1e-9 else 0.0

        decline_rates.append(float(slope))
        noise_ratios.append(nsr)

        # ── RUL-vs-sensor correlation (whole run) ─────────────────────────
        if len(sensor) > 1 and np.std(sensor) > 1e-9 and np.std(rul_col) > 1e-9:
            r, _ = pearsonr(rul_col, sensor)
            rul_correlations.append(float(r))

    return (
        np.array(decline_rates),
        np.array(noise_ratios),
        np.array(rul_correlations),
    )


# ---------------------------------------------------------------------------
# Synthetic CSV helpers
# ---------------------------------------------------------------------------

def load_synthetic(
    filepath: str,
    id_col: str,
    time_col: str,
    value_col: str,
) -> dict[str, np.ndarray]:
    """
    Load the combined synthetic CSV and return a dict mapping
    mission_id → 2-D float array with columns [tick, value, label_fault_type_idx].

    We need the raw label_fault_type string to locate the fault-active window,
    so we store it as a separate list alongside the numeric arrays.
    """
    import csv

    missions_numeric: dict[str, list[tuple[float, float]]] = defaultdict(list)
    missions_labels:  dict[str, list[str]]                 = defaultdict(list)

    with open(filepath, newline="") as f:
        reader = csv.DictReader(f)
        if reader.fieldnames is None:
            sys.exit(f"ERROR: {filepath} appears to be empty or has no header.")

        missing = {id_col, time_col, value_col} - set(reader.fieldnames)
        if missing:
            sys.exit(
                f"ERROR: column(s) {missing} not found in {filepath}.\n"
                f"Available columns: {list(reader.fieldnames)}"
            )

        has_label = "label_fault_type" in reader.fieldnames

        for row in reader:
            mid   = row[id_col]
            tick  = float(row[time_col])
            value = float(row[value_col])
            label = row["label_fault_type"] if has_label else "unknown"
            missions_numeric[mid].append((tick, value))
            missions_labels[mid].append(label)

    result: dict[str, tuple[np.ndarray, list[str]]] = {}
    for mid in missions_numeric:
        arr = np.array(missions_numeric[mid])   # shape (N, 2): [tick, value]
        # sort by tick just in case files were concatenated out of order
        order = np.argsort(arr[:, 0])
        labels_sorted = [missions_labels[mid][i] for i in order]
        result[mid] = (arr[order], labels_sorted)

    return result


def extract_synthetic_signatures(
    missions: dict[str, tuple[np.ndarray, list[str]]],
    window: int = 20,
    early_rul_cap: int = 125,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    For every *fault* mission (label_fault_type != 'healthy'), extract:
      • decline_rates   — per-tick slope over the fault-active window
                          (from fault onset to the last row that still carries
                          a non-healthy label, i.e. before descent/shutdown).
      • noise_ratios    — residual std / |trend mean| over that window.
      • rul_correlations — Pearson r between a synthetic piecewise RUL curve
                           and the sensor column across the whole run.

    Healthy missions are skipped entirely — they have no degradation signal
    to compare against C-MAPSS run-to-failure curves.
    """
    decline_rates:    list[float] = []
    noise_ratios:     list[float] = []
    rul_correlations: list[float] = []

    for mid, (arr, labels) in missions.items():
        # ── Skip healthy missions ─────────────────────────────────────────
        unique_labels = set(labels)
        fault_labels  = unique_labels - {"healthy", "unknown"}
        if not fault_labels:
            continue   # purely healthy mission — nothing to compare

        # ── Locate the fault-active window ────────────────────────────────
        # Find the first row where label != 'healthy' (fault onset index)
        # and the last row where label != 'healthy' (before descent/shutdown
        # throttle changes make the signal drop for non-fault reasons).
        fault_indices = [i for i, lbl in enumerate(labels) if lbl not in ("healthy", "unknown")]

        if len(fault_indices) < 2:
            continue

        onset_idx = fault_indices[0]
        end_idx   = fault_indices[-1]   # last row still in the fault window

        # Take up to `window` rows ending at end_idx
        win_start  = max(onset_idx, end_idx - window + 1)
        sensor_win = arr[win_start : end_idx + 1, 1]   # column 1 = value
        ticks_win  = arr[win_start : end_idx + 1, 0]   # column 0 = tick
        t_norm     = ticks_win - ticks_win[0]           # normalise to 0-based

        if len(sensor_win) < 2:
            continue

        slope, intercept = np.polyfit(t_norm, sensor_win, 1)
        trend     = slope * t_norm + intercept
        residuals = sensor_win - trend
        signal_mean = abs(np.mean(trend))
        nsr = float(np.std(residuals) / signal_mean) if signal_mean > 1e-9 else 0.0

        decline_rates.append(float(slope))
        noise_ratios.append(nsr)

        # ── RUL-vs-sensor correlation (whole run) ─────────────────────────
        n_ticks    = len(arr)
        time_col   = arr[:, 0]
        max_tick   = time_col[-1]
        raw_rul    = max_tick - time_col
        rul_synth  = np.minimum(raw_rul, float(early_rul_cap))
        sensor_all = arr[:, 1]

        if np.std(sensor_all) > 1e-9 and np.std(rul_synth) > 1e-9:
            r, _ = pearsonr(rul_synth, sensor_all)
            rul_correlations.append(float(r))

    return (
        np.array(decline_rates),
        np.array(noise_ratios),
        np.array(rul_correlations),
    )


# ---------------------------------------------------------------------------
# Reporting helpers
# ---------------------------------------------------------------------------

def _fmt_ks(label: str, stat: float, pval: float) -> str:
    verdict = "✅ PASS (p > 0.05)" if pval > 0.05 else "❌ FAIL (p ≤ 0.05)"
    return (
        f"  {label:<30}  statistic={stat:.4f}  p={pval:.4f}  {verdict}"
    )


def _fmt_corr(label: str, arr: np.ndarray) -> str:
    if len(arr) == 0:
        return f"  {label:<30}  n=0  (no data)"
    return (
        f"  {label:<30}  n={len(arr):3d}  "
        f"mean r={np.mean(arr):+.3f}  std={np.std(arr):.3f}"
    )


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Validate AeroTwin synthetic data against NASA C-MAPSS.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument("--cmapss",            required=True,
                        help="Path to C-MAPSS text file (e.g. train_FD001.txt).")
    parser.add_argument("--synthetic",         required=True,
                        help="Path to combined synthetic CSV (all_missions.csv).")
    parser.add_argument("--synthetic-col",     required=True, dest="syn_col",
                        help="Numeric telemetry column to compare (e.g. oil_pressure_bar).")
    parser.add_argument("--synthetic-id-col",  required=True, dest="syn_id_col",
                        help="Column that identifies each mission run (mission_id).")
    parser.add_argument("--synthetic-time-col",required=True, dest="syn_time_col",
                        help="Integer tick/time column within each run (tick).")
    parser.add_argument("--cmapss-sensor",     type=int, default=_CMAPSS_SENSOR_START,
                        dest="cmapss_sensor_col",
                        help=f"0-based column index of the C-MAPSS sensor to use "
                             f"(default={_CMAPSS_SENSOR_START} → sensor_1).")
    parser.add_argument("--window",            type=int, default=20,
                        help="Number of rows in the fault-window signature (default=20).")
    parser.add_argument("--rul-cap",           type=int, default=125,
                        dest="rul_cap",
                        help="Early-RUL cap for piecewise labelling (default=125).")
    args = parser.parse_args()

    # ── Load data ─────────────────────────────────────────────────────────
    print(f"\nLoading C-MAPSS data from:   {args.cmapss}")
    cmapss_units = load_cmapss(args.cmapss)
    print(f"  → {len(cmapss_units)} units loaded.")

    print(f"\nLoading synthetic data from: {args.synthetic}")
    syn_missions = load_synthetic(
        args.synthetic,
        id_col=args.syn_id_col,
        time_col=args.syn_time_col,
        value_col=args.syn_col,
    )
    total_missions = len(syn_missions)
    fault_missions = sum(
        1 for _, (_, labels) in syn_missions.items()
        if any(lbl not in ("healthy", "unknown") for lbl in labels)
    )
    print(f"  → {total_missions} missions loaded "
          f"({fault_missions} fault, {total_missions - fault_missions} healthy).")
    print(f"  → Only fault missions contribute to signature distributions.")

    # ── Extract signatures ─────────────────────────────────────────────────
    print(f"\nExtracting degradation signatures "
          f"(window={args.window} ticks, sensor col={args.cmapss_sensor_col}) …")

    c_decline, c_noise, c_rul_r = extract_cmapss_signatures(
        cmapss_units, sensor_col=args.cmapss_sensor_col, window=args.window
    )
    s_decline, s_noise, s_rul_r = extract_synthetic_signatures(
        syn_missions, window=args.window, early_rul_cap=args.rul_cap
    )

    print(f"  C-MAPSS  : {len(c_decline)} units with valid signatures.")
    print(f"  Synthetic: {len(s_decline)} fault missions with valid signatures.")

    if len(c_decline) == 0 or len(s_decline) == 0:
        print("\nERROR: not enough data to run KS tests.  "
              "Check that the synthetic CSV contains fault missions and that "
              "the column names match.")
        sys.exit(1)

    # ── KS tests ──────────────────────────────────────────────────────────
    print("\n" + "=" * 70)
    print("KS TEST RESULTS — degradation signature distributions")
    print("=" * 70)

    ks_dr  = ks_2samp(c_decline, s_decline)
    ks_nsr = ks_2samp(c_noise,   s_noise)

    print(_fmt_ks("Decline rate",        ks_dr.statistic,  ks_dr.pvalue))
    print(_fmt_ks("Noise-to-signal ratio", ks_nsr.statistic, ks_nsr.pvalue))

    passed = (ks_dr.pvalue > 0.05) and (ks_nsr.pvalue > 0.05)
    overall = "✅ OVERALL PASS" if passed else "❌ OVERALL FAIL"
    print(f"\n  {overall}")
    print(
        "  (p > 0.05 on both tests means synthetic degradation curves are\n"
        "   statistically consistent with real C-MAPSS behaviour.)"
    )

    # ── RUL-vs-parameter correlation ──────────────────────────────────────
    print("\n" + "=" * 70)
    print("RUL-VS-PARAMETER CORRELATION (Pearson r, whole-run)")
    print("=" * 70)
    print(_fmt_corr("C-MAPSS",   c_rul_r))
    print(_fmt_corr("Synthetic", s_rul_r))

    if len(c_rul_r) > 0 and len(s_rul_r) > 0:
        delta = abs(np.mean(c_rul_r) - np.mean(s_rul_r))
        consistency = "✅ consistent" if delta < 0.15 else "⚠️  divergent (Δ > 0.15)"
        print(
            f"\n  |Δ mean r| = {delta:.3f}  →  {consistency}\n"
            "  (A small delta means both datasets show a similarly-shaped\n"
            "   RUL-vs-parameter relationship, validating the synthetic\n"
            "   degradation trajectory.)"
        )

    print()


if __name__ == "__main__":
    main()
